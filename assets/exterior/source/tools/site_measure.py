M_LAT = 111130.0
M_LON = 111320.0 * math.cos(math.radians(40.779))
A = (40.7793443, -73.9624859)
B = (40.7788649, -73.9628349)


def en(p):
    return (p[1] - A[1]) * M_LON, (p[0] - A[0]) * M_LAT


ax, ay = en(B)
ln = math.hypot(ax, ay)
ux, uy = -ax / ln, -ay / ln
nx, ny = uy, -ux
mid = (ax / 2, ay / 2)


def game(p):
    e, n = en(p)
    dx, dy = e - mid[0], n - mid[1]
    return round(dx * ux + dy * uy, 2), round(10.0 + dx * nx + dy * ny, 2)


def parse(t):
    return [tuple(map(float, q.split())) for q in t.split(";")]


